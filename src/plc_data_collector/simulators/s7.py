"""S7 simulator of a press (DB1) and a few merker bytes, for demos and tests.

Run it with ``python -m plc_data_collector.simulators.s7``. It is a
python-snap7 server; the default port is 1102 (unprivileged), and the PLC's
rack/slot are not checked, so the demo Connection uses rack 0, slot 1.

DB1 "PressData" has standard (non-optimized) access. The offsets below were
worked out by hand from the S7 layout rules, not generated by this project's
TIA importer, so they independently check it (``deploy/demo/s7/PressData.db``
is the TIA-style source of this same DB). The rules: Bools pack from bit 0 of
a byte; Byte/Char/SInt/USInt take the next free byte; every other type,
String, Struct, Array and UDT starts on an even byte; a Struct/UDT size rounds
up to even (``Status`` is 2 bytes, ``typeMotor`` is 7 rounded up to 8);
``String[n]`` takes n + 2 bytes. All values are big-endian. The DB is 68 bytes.

<!-- layout:begin -->
| Name | Type | Offset |
| --- | --- | --- |
| Pressure | real | 0 |
| Status.Running | bool | 4.0 |
| Status.Fault | bool | 4.1 |
| Status.DoorClosed | bool | 4.2 |
| Status.Mode | byte | 5 |
| Temps[0] | real | 6 |
| Temps[1] | real | 10 |
| Temps[2] | real | 14 |
| Temps[3] | real | 18 |
| Cycles | dint | 22 |
| RamPosition | int | 26 |
| Energy | lreal | 28 |
| Recipe | string[20] | 36 |
| Motor.Current | real | 58 |
| Motor.Speed | int | 62 |
| Motor.Running | bool | 64.0 |
| Motor.Overheat | bool | 64.1 |
| Batch | uint | 66 |
<!-- layout:end -->

What the values do (``simulated_image`` computes them from the elapsed time):

* ``Pressure`` bar, 150 +- 20 (sine, 45 s); ``Temps[0..3]`` degC around 60;
  ``Energy`` grows; ``Cycles`` +1 every 0.5 s; ``Batch`` +1 every 10 s
* ``Status.Running`` / ``Status.Fault`` swap for 5 s every minute;
  ``Status.DoorClosed`` is always true; ``Status.Mode`` cycles 1, 2, 3
* ``RamPosition`` mm times 10 (0-1000); ``Recipe`` is ``RCP-0042``
* ``Motor.Current`` A, ``Motor.Speed`` rpm; ``Motor.Overheat`` is always false

Merker area M (16 bytes): ``M0.0`` lamp (toggles every 5 s), ``M0.1`` always
true, ``M2`` int, a signed sine -100..100 (word MW2).

The server answers reads on its own threads. An update takes the area lock the
server holds while it reads (``Server.lock_area``) and replaces the whole area
in one step, so a read never sees a half-written multi-byte value.
"""

from __future__ import annotations

import argparse
import asyncio
import logging
import math
import os
import random
import struct
import time
from collections.abc import Sequence
from dataclasses import dataclass

from snap7.server import Server
from snap7.type import SrvArea

from plc_data_collector.app.logging import configure_logging
from plc_data_collector.app.service import install_signal_handlers

LOGGER = logging.getLogger("plc_data_collector.simulators.s7")

DB_NUMBER = 1
DB1_SIZE = 68
MERKER_SIZE = 16
RECIPE_NAME = "RCP-0042"
RECIPE_LENGTH = 20
PRESSURE_PERIOD_S = 45.0
RAM_PERIOD_S = 10.0
FAULT_PERIOD_S = 60.0
FAULT_DURATION_S = 5.0


@dataclass(frozen=True)
class Image:
    """The simulated memory of DB1 and of the merker area."""

    db1: bytes
    merkers: bytes


def _bits(*flags: bool) -> int:
    return sum(1 << bit for bit, flag in enumerate(flags) if flag)


def simulated_image(elapsed_s: float, rng: random.Random | None = None) -> Image:
    """Return the simulated memory ``elapsed_s`` seconds after start."""
    rng = rng or random.Random()
    wave = 2 * math.pi * elapsed_s
    pressure = (
        150.0 + 20.0 * math.sin(wave / PRESSURE_PERIOD_S) + rng.uniform(-0.5, 0.5)
    )
    fault = elapsed_s % FAULT_PERIOD_S >= FAULT_PERIOD_S - FAULT_DURATION_S
    ram = round(50.0 + 50.0 * math.sin(wave / RAM_PERIOD_S), 1)
    db = bytearray(DB1_SIZE)
    struct.pack_into(">f", db, 0, pressure)
    db[4] = _bits(not fault, fault, True)
    db[5] = 1 + int(elapsed_s // 10) % 3
    for index in range(4):
        temperature = (
            60.0 + 10.0 * math.sin(wave / 120.0 + index) + rng.uniform(-0.3, 0.3)
        )
        struct.pack_into(">f", db, 6 + 4 * index, temperature)
    struct.pack_into(">i", db, 22, int(elapsed_s // 0.5))
    struct.pack_into(">h", db, 26, round(ram * 10))
    struct.pack_into(">d", db, 28, 12345.6 + elapsed_s * 0.5)
    text = RECIPE_NAME.encode("latin-1")
    db[36:38] = bytes((RECIPE_LENGTH, len(text)))
    db[38 : 38 + len(text)] = text
    struct.pack_into(">f", db, 58, 12.0 + 3.0 * math.sin(wave / PRESSURE_PERIOD_S))
    struct.pack_into(">h", db, 62, round(1450 + 50 * math.sin(wave / 20.0)))
    db[64] = _bits(not fault, False)
    struct.pack_into(">H", db, 66, 1000 + int(elapsed_s // 10))
    merkers = bytearray(MERKER_SIZE)
    merkers[0] = _bits(int(elapsed_s // 5) % 2 == 0, True)
    struct.pack_into(">h", merkers, 2, round(100 * math.sin(wave / 30.0)))
    return Image(bytes(db), bytes(merkers))


def _publish(server: Server, area_data: dict[int, bytearray], image: Image) -> None:
    """Replace the registered memory in one step, under the server's area lock."""
    for area, index, buffer, data in (
        (SrvArea.DB, DB_NUMBER, area_data[0], image.db1),
        (SrvArea.MK, 0, area_data[1], image.merkers),
    ):
        server.lock_area(area, index)
        try:
            buffer[:] = data
        finally:
            server.unlock_area(area, index)


async def run_simulator(
    *,
    host: str = "0.0.0.0",
    port: int = 1102,
    update_interval_s: float = 1.0,
    stop_event: asyncio.Event | None = None,
) -> None:
    """Serve the simulated press until ``stop_event`` is set."""
    stop = asyncio.Event() if stop_event is None else stop_event
    rng = random.Random()
    initial = simulated_image(0.0, rng)
    db1 = bytearray(initial.db1)
    merkers = bytearray(initial.merkers)
    server = Server(log=False)
    server.register_area(SrvArea.DB, DB_NUMBER, db1)
    server.register_area(SrvArea.MK, 0, merkers)
    server.start_to(host, port)
    try:
        LOGGER.info("simulator_started", extra={"host": host, "port": port})
        started = time.monotonic()
        while not stop.is_set():
            try:
                await asyncio.wait_for(stop.wait(), timeout=update_interval_s)
            except TimeoutError:
                image = simulated_image(time.monotonic() - started, rng)
                _publish(server, {0: db1, 1: merkers}, image)
        LOGGER.info("simulator_stopping")
    finally:
        await asyncio.to_thread(server.destroy)
    LOGGER.info("simulator_stopped")


def build_parser() -> argparse.ArgumentParser:
    """Build the simulator command line parser."""
    parser = argparse.ArgumentParser(
        prog="python -m plc_data_collector.simulators.s7",
        description="S7 simulator of a press (DB1) and a few merker bytes.",
    )
    parser.add_argument("--host", default=os.environ.get("S7_SIM_HOST", "0.0.0.0"))
    parser.add_argument(
        "--port", type=int, default=int(os.environ.get("S7_SIM_PORT", "1102"))
    )
    parser.add_argument("--update-interval", type=float, default=1.0)
    return parser


async def _serve(host: str, port: int, update_interval_s: float) -> None:
    stop_event = asyncio.Event()
    callbacks = install_signal_handlers(stop_event)
    try:
        await run_simulator(
            host=host,
            port=port,
            update_interval_s=update_interval_s,
            stop_event=stop_event,
        )
    finally:
        for callback in callbacks:
            callback()


def main(argv: Sequence[str] | None = None) -> int:
    """Run the simulator until SIGTERM or SIGINT."""
    args = build_parser().parse_args(argv)
    configure_logging()
    asyncio.run(_serve(args.host, args.port, args.update_interval))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
